#ifndef SECURITY_H

#define SECURITY_H

#include "esp_err.h"
#include "uuid.h"

/*
 * Thread safety: every function of the security layer holds an internal mutex while it runs, so they can be called
 * from different tasks. Each call is atomic, but a sequence of calls is not. For example, the state read with
 * security_get_context() can change before the next call, as it is only a snapshot.
 */

/**
 * @brief Lifecycle state of the device credentials. It decides what the device allows, such as when it creates a new CSR.
 */
typedef enum
{
    /** The device has no certificate stored. It cannot authenticate with other services. */
    SECURITY_STATE_UNPROVISIONED,

    /** The device has generated its CSR and is waiting for the user to install the certificate. */
    SECURITY_STATE_ENROLLING,

    /** The device has a valid certificate. It can authenticate with other services. */
    SECURITY_STATE_ACTIVE,

    /** The device has requested a new certificate and is waiting for the result. The current certificate is still valid. */
    SECURITY_STATE_RENEWING,

    /** The certificate expired before the renewal succeeded. The device must be enrolled again. */
    SECURITY_STATE_EXPIRED,

    /** The certificate was revoked. The device must be enrolled again. */
    SECURITY_STATE_REVOKED
} security_state_t;

typedef struct {
    uuid_t identity;
    security_state_t state;
} security_context_t;

/**
 *
 * @brief Initializes the security layer, preparing the device to authenticate with other services.
 *
 * Storage must be initialized before calling this function. On the first boot it generates the device identity and
 * saves it, so it stays the same across reboots. On every boot it loads the lifecycle state saved in flash, or starts
 * as UNPROVISIONED when none is saved.
 *
 * This function creates or loads the security context, which contains the device identity and lifecycle state.
 * It must be called only once, calling it again returns ESP_ERR_INVALID_STATE. If it fails, the security layer is
 * left not initialized.
 *
 * @return ESP_OK on successful initialization, ESP_ERR_INVALID_STATE when storage is not initialized or the security
 * layer is already initialized, or an appropriate error code on failure.
 */
esp_err_t security_init();

/**
 *
 * @brief Gets the security context, which contains the device identity and lifecycle state.
 *
 * The caller gets a snapshot, a copy of the context at the time of the call. It does not change if the state changes
 * afterwards.
 *
 * @param context the pointer to the security context to be filled. It must be allocated by the caller.
 * @return ESP_OK on success or ESP_ERR_INVALID_STATE when the security layer is not initialized.
 */
esp_err_t security_get_context(security_context_t *context);

/**
 *
 * @brief Starts the enrollment process for the device.
 *
 * The device must be in the UNPROVISIONED state, or in the EXPIRED or REVOKED state to enroll again. It generates a
 * new private key and a CSR signed with it, and saves the CSR in flash. The private key is kept in the PSA key store
 * and never leaves it, it is only used through its id. If the device already had a private key, it is replaced.
 * The device then transitions to the ENROLLING state, waiting for the certificate issued from the CSR to be installed
 * with security_install_certificate().
 *
 * @return ESP_OK on success, ESP_ERR_INVALID_STATE when the security layer is not initialized or the device is not in
 * the UNPROVISIONED, EXPIRED or REVOKED state, or an appropriate error code on failure.
 */
esp_err_t security_start_enrollment();

/**
 *
 * @brief Installs the certificate issued from the CSR generated by security_start_enrollment().
 *
 * The device must be in the ENROLLING state. The certificate is only accepted when all of the following are true:
 * - it is a well formed PEM encoded X.509 certificate;
 * - its public key belongs to the device private key;
 * - the current time is inside its validity period, so the system clock must be set (for example by SNTP) before
 *   calling this function.
 *
 * @param cert_pem the certificate in PEM format, null terminated.
 * @return ESP_OK on success, ESP_ERR_INVALID_STATE when the security layer is not initialized or the device is not in
 * the ENROLLING state, ESP_ERR_INVALID_ARG when the certificate is malformed, does not match the device private key,
 * is expired or is not yet valid, or an appropriate error code on failure.
 */
esp_err_t security_install_certificate(const char *cert_pem);

/**
 *
 * @brief Revokes the device, so it stops being trusted to authenticate with other services.
 *
 * The device must be in the ACTIVE or RENEWING state. It deletes the private key, the certificate and the CSR, and
 * only after that the device transitions to the REVOKED state, which is saved in flash, so it stays revoked across
 * reboots. It must be enrolled again to get new credentials.
 *
 * If deleting one of them fails, the error is returned and the state does not change. Some credentials may already be
 * deleted, so calling this function again is safe: what is already deleted is skipped.
 *
 * This function does not tell the issuer of the certificate, which must revoke it on its side.
 *
 * @return ESP_OK on success, ESP_ERR_INVALID_STATE when the security layer is not initialized or the device is not in
 * the ACTIVE or RENEWING state, or an appropriate error code on failure.
 */
esp_err_t security_revoke();

/**
 *
 * @brief Retrieves the certificate installed by security_install_certificate().
 *
 * The device must be in the ACTIVE or RENEWING state. The certificate is returned even when it is expired. If it is
 * expired and the device is in the ACTIVE state, the device transitions to the RENEWING state, which is saved in flash.
 * The system clock must be set (for example by SNTP) before calling this function, otherwise a valid certificate may
 * look not yet valid.
 *
 * The memory for the certificate is allocated by this function, the caller must release it with free().
 *
 * @param out_pem the pointer to be set to the allocated certificate in PEM format, null terminated. It is only set on
 * success.
 * @return ESP_OK on success, ESP_ERR_INVALID_STATE when the security layer is not initialized or the device is not in
 * the ACTIVE or RENEWING state, ESP_ERR_INVALID_ARG when @p out_pem is null, or an appropriate error code on failure.
 */
esp_err_t security_get_certificate(char **out_pem);

#endif
